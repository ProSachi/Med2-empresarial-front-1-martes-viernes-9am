let key = parseInt(prompt("ingrese una opción de 1 a 5"));

switch (key) {
    case 1:
        console.log("Selecciono la opción1");
        break;
    case 2:
        console.log("Selecciono la opción2");
        break;
    case 3:
        console.log("Selecciono la opción3");
        break;
    case 4:
        console.log("Selecciono la opción4");
        break;
    case 5:
        console.log("Selecciono la opción5");
        break;
    default:
        console.log("opción default");
        break;
}